static HAL_StatusTypeDef ssd_cmd(uint8_t c)
{
  /* 控制字节 0x00 = 后面是命令 */
  return HAL_I2C_Mem_Write(&hi2c1, SSD1306_ADDR, 0x00, I2C_MEMADD_SIZE_8BIT, &c, 1, 20);
}

static HAL_StatusTypeDef ssd_data(const uint8_t *d, uint16_t n)
{
  /* 控制字节 0x40 = 后面是显存数据（连续流） */
  return HAL_I2C_Mem_Write(&hi2c1, SSD1306_ADDR, 0x40, I2C_MEMADD_SIZE_8BIT,
                           (uint8_t *)d, n, 50);
}

uint8_t SSD1306_IsOK(void)
{
  return dev_ok;
}

void SSD1306_Init(void)
{
  static const uint8_t seq[] = {
    0xAE,             /* 关显示 */
    0xD5, 0x80,       /* 时钟分频 */
    0xA8, 0x3F,       /* 复用率 63（64 行） */
    0xD3, 0x00,       /* 显示偏移 0 */
    0x40,             /* 起始行 0 */
    0x8D, 0x14,       /* 内部升压开 */
    0x20, 0x00,       /* 横向寻址模式 */
    0xA1,             /* 段重映射（左右翻转） */
    0xC8,             /* COM 扫描方向（上下翻转） */
    0xDA, 0x12,       /* COM 引脚配置（128x64 用 0x12） */
    0x81, 0xCF,       /* 对比度 */
    0xD9, 0xF1,       /* 预充电周期 */
    0xDB, 0x40,       /* VCOMH 电平 */
    0xA4,             /* 显示 RAM 内容（非全亮） */
    0xA6,             /* 正常显示（非反色） */
    0xAF,             /* 开显示 */
  };
  if (HAL_I2C_IsDeviceReady(&hi2c1, SSD1306_ADDR, 3, 100) != HAL_OK)
  {
    dev_ok = 0;                    /* 屏没接/地址不对：跳过，不卡任务 */
    return;
  }
  for (uint32_t i = 0; i < sizeof(seq); i++)
  {
    (void)ssd_cmd(seq[i]);
  }
  dev_ok = 1;
  SSD1306_Fill(0x00);
  SSD1306_Flush();
}

void SSD1306_Fill(uint8_t pattern)
{
  memset(fb, pattern, sizeof(fb));
}

static void set_pixel(uint8_t x, uint8_t y)
{
  if (x >= SSD1306_W || y >= SSD1306_H) return;
  fb[x + (y >> 3) * SSD1306_W] |= (uint8_t)(1u << (y & 7));
}

void SSD1306_DrawChar(uint8_t x, uint8_t y, char c, uint8_t scale)
{
  if (c < 32 || c > 126) c = '?';
  const uint8_t *g = &font5x7[(c - 32) * 5];
  for (uint8_t col = 0; col < 5; col++)
  {
    for (uint8_t row = 0; row < 8; row++)
    {
      if (g[col] & (1u << row))
      {
        for (uint8_t sx = 0; sx < scale; sx++)
          for (uint8_t sy = 0; sy < scale; sy++)
            set_pixel((uint8_t)(x + col * scale + sx), (uint8_t)(y + row * scale + sy));
      }
    }
  }
}

void SSD1306_DrawString(uint8_t x, uint8_t y, const char *s, uint8_t scale)
{
  while (*s)
  {
    SSD1306_DrawChar(x, y, *s++, scale);
    x = (uint8_t)(x + 6 * scale);          /* 5 列字形 + 1 列空隙 */
  }
}

void SSD1306_Flush(void)
{
  if (!dev_ok) return;
  (void)ssd_cmd(0x21); (void)ssd_cmd(0);   (void)ssd_cmd(127);  /* 列范围 0~127 */
  (void)ssd_cmd(0x22); (void)ssd_cmd(0);   (void)ssd_cmd(7);    /* 页范围 0~7 */
  for (uint8_t p = 0; p < 8; p++)
  {
    (void)ssd_data(&fb[p * SSD1306_W], SSD1306_W);
  }
}
